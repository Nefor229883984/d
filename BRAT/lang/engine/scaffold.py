"""Project templates behind `brat new`.

Every template is a plain string constant: `brat new` must work in a bare
checkout with no packaging metadata, no setup step and no network. The two
kinds are deliberately small -- they exist so that the first `brat new` in a
fresh clone produces a program that runs, checks and builds, instead of a
`fn main() -> i64 { return 0 }` stub that proves nothing.
"""

import os

SERVICE = "service"
TOOL = "tool"
KINDS = (SERVICE, TOOL)
DEFAULT_KIND = SERVICE

TOKEN = "__NAME__"

MAIN_SERVICE = r'''// __NAME__ -- TCP service skeleton generated by `brat new`.
//
// Run it:  brat run __NAME__/main.brat
// Try it:  from another terminal, send one line:
//            printf 'ping\n' | nc 127.0.0.1 8088
//
// It listens on 127.0.0.1:8088 and answers every connection with "ok". It stops
// after max_requests answers so a demo run ends by itself; remove that limit
// for a service that should run until it is killed.

enum Res {
  Ok(v),
  Err(reason)
}

fn answer(conn: i64) -> Res {
  let got = tcp_recv(conn, 256)
  match got {
    Ok(text) => {
      if text == "" {
        tcp_close(conn)
        return Err("peer closed before sending")
      }
      log.info("request of {len(text)} bytes")
      let sent = tcp_send(conn, "ok\n")
      tcp_close(conn)
      match sent {
        Ok(n) => {
          return Ok(n)
        },
        Err(reason) => {
          return Err(reason)
        }
      }
    },
    Err(reason) => {
      tcp_close(conn)
      return Err(reason)
    }
  }
  return Err("unreachable")
}

fn main() -> i64 {
  let addr = "127.0.0.1:8088"
  let max_requests = 2
  let mut served = 0
  let mut failed = 0
  let srv = tcp_listen(addr)
  match srv {
    Ok(fd) => {
      log.info("listening on {addr}")
      while served < max_requests {
        let acc = tcp_accept(fd)
        match acc {
          Ok(conn) => {
            let r = answer(conn)
            match r {
              Ok(n) => {
                served = served + 1
              },
              Err(reason) => {
                failed = failed + 1
                log.warn("request failed: {reason}")
              }
            }
          },
          Err(reason) => {
            log.error("accept failed: {reason}")
            tcp_close(fd)
            return 1
          }
        }
      }
      tcp_close(fd)
      print("served={served} failed={failed}")
      return 0
    },
    Err(reason) => {
      log.error("cannot listen on {addr}: {reason}")
      return 1
    }
  }
  return 0
}
'''


MAIN_TOOL = '''// __NAME__ -- command-line tool generated by `brat new`.
//
// Run it:  brat run __NAME__/main.brat
// Try:     brat run __NAME__/main.brat -- notes.txt

enum Res {
  Ok(v),
  Err(e)
}

enum Entry {
  Field(key, val),
  Skip(raw),
  Bad(raw)
}

fn parse_line(line: str) -> Entry {
  let text = line.trim()
  if text.starts_with("#") || len(text) == 0 {
    return Skip(text)
  }
  let parts = text.split(":")
  if len(parts) < 2 {
    return Bad(text)
  }
  return Field(parts[0].trim(), parts[1].trim())
}

fn load(path: str) -> Res {
  let got = read_file(path)
  match got {
    Ok(text) => {
      log.info("read {path} ({len(text)} bytes)")
      return Ok(text.lines())
    },
    Err(reason) => {
      log.warn("cannot read {path}: {reason}")
      return Err(reason)
    }
  }
  return Err("unreachable")
}

fn main() -> i64 {
  let mut lines = ["# comment", "host: 127.0.0.1", "port: 9001", "broken line"]
  let mut given = args()
  if len(given) > 0 {
    let got = load(given[0])
    match got {
      Ok(from_file) => {
        lines = from_file
      },
      Err(reason) => {
        log.warn("keeping the built-in sample: {reason}")
      }
    }
  }

  let mut fields = {}
  let mut skipped = 0
  let mut broken = 0
  for line in lines {
    let e = parse_line(line)
    match e {
      Field(key, val) => {
        fields.set(key, val)
        log.info("field {key}={val}")
      },
      Skip(raw) => {
        skipped = skipped + 1
      },
      Bad(raw) => {
        broken = broken + 1
        log.warn("bad line: {raw}")
      }
    }
  }

  print("fields={len(fields.keys())} skipped={skipped} broken={broken}")
  print("host={fields.get("host")} port={fields.get("port")}")
  return 0
}
'''

MAIN_TEMPLATES = {
    SERVICE: MAIN_SERVICE,
    TOOL: MAIN_TOOL,
}

BLURB = {
    SERVICE: "TCP service skeleton",
    TOOL: "tool for parsing `key: value` lines",
}

README = '''# __NAME__

A BRAT __BLURB__, scaffolded by `brat new`. Zero dependencies: it also
demonstrates "{expr}" interpolation, log.info, match on
Ok/Err, and vec/map -- the pieces every BRAT program reuses.

Run:   brat run __NAME__/main.brat
Check: brat check __NAME__/main.brat
Build: brat build __NAME__/main.brat
Next:  lang/examples/ has ~70 working programs, lang/spec/SPEC.md is the law.
'''


class ScaffoldError(Exception):
    """A scaffold request refused cleanly: the caller prints it and exits 1."""


def check_name(name):
    """Reject anything that is not a single plain directory name."""
    if not name:
        raise ScaffoldError("NAME is required")
    if name != name.strip() or name in (".", ".."):
        raise ScaffoldError("bad project name %r" % (name,))
    if any(c in name for c in "/\\:*?\"<>|") or name[0] in "-.":
        raise ScaffoldError("bad project name %r" % (name,))
    if len(name) > 64:
        raise ScaffoldError("project name too long (%d chars)" % len(name))
    return name


def render_main(name, kind):
    if kind not in MAIN_TEMPLATES:
        raise ScaffoldError("unknown kind %r (want %s)" % (kind, "|".join(KINDS)))
    check_name(name)
    return MAIN_TEMPLATES[kind].replace(TOKEN, name)


def render_readme(name, kind):
    if kind not in MAIN_TEMPLATES:
        raise ScaffoldError("unknown kind %r (want %s)" % (kind, "|".join(KINDS)))
    return README.replace(TOKEN, name).replace("__BLURB__", BLURB[kind])


def project_files(name, kind):
    """[(file name, contents)] for a fresh project, in creation order."""
    return [
        ("main.brat", render_main(name, kind)),
        ("README.md", render_readme(name, kind)),
    ]


def _safe_rel(rel):
    """Reject a relative path that escapes the target directory.

    `..` segments or an absolute path would let `write_project` write outside
    `root/name/`, so refuse them loudly instead of silently writing somewhere
    else.
    """
    if os.path.isabs(rel):
        raise ScaffoldError("unsafe file path %r (absolute)" % (rel,))
    parts = rel.replace("\\", "/").split("/")
    if ".." in parts or "." in parts:
        raise ScaffoldError("unsafe file path %r (escapes directory)" % (rel,))
    return rel


def write_project(name, kind=DEFAULT_KIND, root=None):
    """Create root/name/ with a runnable project. Returns the written paths."""
    if kind not in MAIN_TEMPLATES:
        raise ScaffoldError("unknown kind %r (want %s)" % (kind, "|".join(KINDS)))
    check_name(name)
    if root is None:
        root = os.getcwd()
    target = os.path.join(root, name)
    if os.path.exists(target):
        raise ScaffoldError("%s already exists" % (target,))
    os.makedirs(target)
    written = []
    try:
        for rel, text in project_files(name, kind):
            rel = _safe_rel(rel)
            with open(os.path.join(target, rel), "w",
                      encoding="utf-8", newline="\n") as f:
                f.write(text)
            written.append(os.path.join(name, rel).replace("\\", "/"))
    except OSError as e:
        raise ScaffoldError(str(e))
    return written


def run_hint(name, cli_path, root=None):
    """The two commands a user runs next, as a list of lines.

    `brat run main.brat` assumes `brat` is on PATH (it is after the project is
    built); the old `python -X utf8 lang/engine/cli.py run ...` invocation
    leaked the repo layout into the hint.
    """
    if root is None:
        root = os.getcwd()
    return [
        "cd %s" % name,
        "brat run main.brat",
    ]